-- 449: Least-privilege ACL for contracts, contract_signers, contract_templates,
--      whatsapp_channels, waiver_templates, and signed_waivers
--
-- Problem A (staging) — contracts/contract_signers/contract_templates/waiver_templates have NO
--   grants for authenticated. Every dashboard query returns a swallowed 42501
--   that shows as an empty list.
-- Problem B (production) — these same tables have BROAD table-level grants to
--   authenticated (via ALTER DEFAULT PRIVILEGES), which is too permissive.
-- Problem C (both envs) — whatsapp_channels grants authenticated table-level
--   SELECT (M293), meaning meta_access_token is readable by any authenticated
--   session including admin sessions via the is_admin RLS policy.
--
-- Target shape after this migration:
--   contracts / contract_signers:
--     service_role  → SELECT, INSERT, UPDATE, DELETE
--     authenticated → column-level SELECT (non-credential columns only) +
--                     column-level INSERT + UPDATE (no token/OTP/server-managed cols)
--                     RLS "Business owners manage their contracts/signers" still applies
--     anon          → nothing
--
--   contract_templates:
--     service_role  → SELECT, INSERT, UPDATE, DELETE
--     authenticated → column-level SELECT + INSERT + UPDATE + DELETE
--                     RLS "Business owners manage templates" still applies
--     anon          → nothing
--
--   whatsapp_channels:
--     service_role  → SELECT, INSERT, UPDATE, DELETE (unchanged from M293)
--     authenticated → column-level SELECT on metadata-only columns
--                     (meta_access_token excluded)
--                     NO UPDATE — all channel mutations are server-side (service_role)
--                     NO INSERT, NO DELETE
--     anon          → nothing (unchanged from M293)
--
--   waiver_templates:
--     service_role  → SELECT, INSERT, UPDATE, DELETE
--     authenticated → column-level SELECT + INSERT + UPDATE
--                     (token auto-generated by DEFAULT; not in INSERT/UPDATE list)
--                     RLS "owners_manage_waiver_templates" gates rows
--     anon          → nothing
--
--   signed_waivers:
--     service_role  → SELECT, INSERT, UPDATE, DELETE
--     authenticated → column-level SELECT only
--                     Signing is public (via /api/waivers/sign using service_role)
--     anon          → nothing
--
-- Idempotent: GRANT is a no-op if the privilege already exists; REVOKE is a
-- no-op if the privilege does not exist.

-- ══════════════════════════════════════════════════════════════════════════════
-- 1. contracts
-- ══════════════════════════════════════════════════════════════════════════════

-- Clean-slate for anon and authenticated (removes broad ALTER DEFAULT PRIVILEGES
-- grants on production; is a no-op on staging where none were granted).
REVOKE ALL ON public.contracts FROM anon;
REVOKE ALL ON public.contracts FROM authenticated;

-- service_role: full CRUD (M415 already grants SELECT/INSERT/UPDATE; add DELETE
-- so revoke/hard-delete paths work via service client).
GRANT SELECT, INSERT, UPDATE, DELETE ON public.contracts TO service_role;

-- authenticated: column-level SELECT — every column the dashboard reads.
-- Excluded: token (the signing URL token — send route uses service_role; dashboard
-- does not select it directly from the contracts table).
GRANT SELECT (
  id, business_id, title, template_url, signed_url,
  signer_name, signer_phone, signer_email,
  token_expires_at, status,
  signature_data, audit_trail, metadata, signed_at,
  created_at, updated_at, document_content,
  signing_mode, require_otp,
  wa_message_id, wa_delivery_status, wa_status_updated_at,
  reference_code, declined_at, decline_reason
) ON public.contracts TO authenticated;

-- authenticated: column-level INSERT/UPDATE
-- Excluded: token, token_expires_at (generated by send route via service_role),
--           signature_data (set during signing via service_role submit route),
--           audit_trail (set during signing via service_role submit route).
GRANT INSERT (
  business_id, title, template_url, signed_url,
  signer_name, signer_phone, signer_email,
  status, metadata, signed_at,
  document_content, signing_mode, require_otp,
  wa_message_id, wa_delivery_status, wa_status_updated_at,
  reference_code, declined_at, decline_reason
) ON public.contracts TO authenticated;

GRANT UPDATE (
  title, template_url, signed_url,
  signer_name, signer_phone, signer_email,
  status, metadata, signed_at,
  updated_at, document_content, signing_mode, require_otp,
  wa_message_id, wa_delivery_status, wa_status_updated_at,
  reference_code, declined_at, decline_reason
) ON public.contracts TO authenticated;

-- ══════════════════════════════════════════════════════════════════════════════
-- 2. contract_signers
-- ══════════════════════════════════════════════════════════════════════════════

REVOKE ALL ON public.contract_signers FROM anon;
REVOKE ALL ON public.contract_signers FROM authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.contract_signers TO service_role;

-- authenticated SELECT: includes token (dashboard uses it to construct signing URLs)
-- but excludes otp_code (the actual OTP value sent to the signer — sensitive).
GRANT SELECT (
  id, contract_id, signer_name, signer_phone, signer_email, signing_order,
  token, token_expires_at, status,
  signature_data, signed_at, audit_trail,
  otp_expires_at, otp_verified, otp_attempts,
  decline_reason, declined_at,
  reminder_24h_sent, reminder_48h_sent,
  created_at, updated_at,
  wa_message_id, wa_delivery_status, wa_status_updated_at
) ON public.contract_signers TO authenticated;

-- authenticated INSERT/UPDATE: excludes token/token_expires_at (generated by send
-- route via service_role), otp_code (set server-side), signature_data (set during
-- signing via service_role), and audit_trail (set during signing via service_role).
GRANT INSERT (
  contract_id, signer_name, signer_phone, signer_email, signing_order,
  status, signed_at,
  otp_expires_at, otp_verified, otp_attempts,
  decline_reason, declined_at,
  reminder_24h_sent, reminder_48h_sent,
  wa_message_id, wa_delivery_status, wa_status_updated_at
) ON public.contract_signers TO authenticated;

GRANT UPDATE (
  signer_name, signer_phone, signer_email, signing_order,
  status, signed_at,
  otp_expires_at, otp_verified, otp_attempts,
  decline_reason, declined_at,
  reminder_24h_sent, reminder_48h_sent,
  updated_at,
  wa_message_id, wa_delivery_status, wa_status_updated_at
) ON public.contract_signers TO authenticated;

-- ══════════════════════════════════════════════════════════════════════════════
-- 3. contract_templates
-- ══════════════════════════════════════════════════════════════════════════════

REVOKE ALL ON public.contract_templates FROM anon;
REVOKE ALL ON public.contract_templates FROM authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.contract_templates TO service_role;

-- authenticated needs DELETE: /api/contracts/templates DELETE route uses the
-- SSR createClient() (authenticated role), not createServiceClient().
GRANT SELECT (
  id, business_id, title, content, template_url, category, created_at, updated_at
) ON public.contract_templates TO authenticated;

GRANT INSERT (
  business_id, title, content, template_url, category
) ON public.contract_templates TO authenticated;

GRANT UPDATE (
  title, content, template_url, category, updated_at
) ON public.contract_templates TO authenticated;

GRANT DELETE ON public.contract_templates TO authenticated;

-- ══════════════════════════════════════════════════════════════════════════════
-- 4. whatsapp_channels
-- ══════════════════════════════════════════════════════════════════════════════

-- Revoke the broad table-level SELECT that M293 granted to authenticated.
-- This eliminates authenticated access to meta_access_token (the Cloud API
-- long-lived System User token) and to admin-session reads of shared-channel
-- credentials via the is_admin RLS policy.
REVOKE ALL ON public.whatsapp_channels FROM anon;
REVOKE ALL ON public.whatsapp_channels FROM authenticated;

-- service_role: full access (unchanged — M293 already grants all four).
GRANT SELECT, INSERT, UPDATE, DELETE ON public.whatsapp_channels TO service_role;

-- authenticated: column-level SELECT on metadata-only columns.
-- Excluded: meta_access_token (long-lived Cloud API token — credential).
-- All of the columns below are safe display/routing metadata with no secret value.
GRANT SELECT (
  id, country_code, phone_number, channel_type, business_id, is_active,
  created_at, updated_at, provider, waba_id, phone_number_id,
  meta_token_expires_at, display_name, quality_rating, messaging_limit,
  connection_method, connection_status
) ON public.whatsapp_channels TO authenticated;

-- No UPDATE, INSERT, or DELETE for authenticated on whatsapp_channels.
-- Verified: all channel mutations (add-number, embedded-signup, channels/request)
-- use createServiceClient() — no authenticated-session write path exists.

-- ══════════════════════════════════════════════════════════════════════════════
-- 5. waiver_templates
-- ══════════════════════════════════════════════════════════════════════════════

-- M186 created waiver_templates with no explicit authenticated grants.
-- On production these inherited broad ALTER DEFAULT PRIVILEGES grants.
-- On staging they had no authenticated grants (same asymmetry as contracts).
-- /api/waivers/templates uses SSR createClient() for GET, POST, PATCH, and
-- the soft-delete PATCH — all via the authenticated role.

REVOKE ALL ON public.waiver_templates FROM anon;
REVOKE ALL ON public.waiver_templates FROM authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.waiver_templates TO service_role;

-- token is a public signing URL token (auto-generated by DEFAULT on INSERT;
-- shown in the dashboard for QR codes / copy link). Not a credential. In SELECT.
-- Excluded from INSERT/UPDATE — the DEFAULT clause handles token generation.
GRANT SELECT (
  id, business_id, title, body, fields, is_active, require_before_booking,
  token, pdf_url, created_at, updated_at
) ON public.waiver_templates TO authenticated;

GRANT INSERT (
  business_id, title, body, fields, is_active, require_before_booking, pdf_url
) ON public.waiver_templates TO authenticated;

GRANT UPDATE (
  title, body, fields, is_active, require_before_booking, pdf_url, updated_at
) ON public.waiver_templates TO authenticated;

-- ══════════════════════════════════════════════════════════════════════════════
-- 6. signed_waivers
-- ══════════════════════════════════════════════════════════════════════════════

-- M186 created signed_waivers. The public signing flow (/api/waivers/sign) uses
-- service_role. The dashboard reads signed_waivers via browser createClient()
-- (for count query) and via SSR createClient() (/api/waivers/signed GET).
-- No authenticated INSERT or UPDATE path exists — signing is service_role only.

REVOKE ALL ON public.signed_waivers FROM anon;
REVOKE ALL ON public.signed_waivers FROM authenticated;

GRANT SELECT, INSERT, UPDATE, DELETE ON public.signed_waivers TO service_role;

-- access_token (M189): a per-signed-waiver display token shown in the dashboard
-- for public access. Not a signing credential. Included in SELECT.
GRANT SELECT (
  id, template_id, business_id, customer_name, customer_phone, customer_email,
  signature_url, signed_at, pdf_url, metadata, audit_trail, created_at, access_token
) ON public.signed_waivers TO authenticated;

-- No INSERT or DELETE for authenticated. Signing and deletion are server-side
-- operations via service_role.

-- ══════════════════════════════════════════════════════════════════════════════
-- 7. Self-check
-- ══════════════════════════════════════════════════════════════════════════════

DO $$
BEGIN
  -- ── 7.1 anon must have no privilege on any of the six tables ─────────────

  IF has_table_privilege('anon', 'public.contracts', 'SELECT') THEN
    RAISE EXCEPTION '449 SELF-CHECK FAILED: anon retains SELECT on contracts';
  END IF;

  IF has_table_privilege('anon', 'public.contract_signers', 'SELECT') THEN
    RAISE EXCEPTION '449 SELF-CHECK FAILED: anon retains SELECT on contract_signers';
  END IF;

  IF has_table_privilege('anon', 'public.contract_templates', 'SELECT') THEN
    RAISE EXCEPTION '449 SELF-CHECK FAILED: anon retains SELECT on contract_templates';
  END IF;

  IF has_table_privilege('anon', 'public.whatsapp_channels', 'SELECT') THEN
    RAISE EXCEPTION '449 SELF-CHECK FAILED: anon retains SELECT on whatsapp_channels';
  END IF;

  IF has_table_privilege('anon', 'public.waiver_templates', 'SELECT') THEN
    RAISE EXCEPTION '449 SELF-CHECK FAILED: anon retains SELECT on waiver_templates';
  END IF;

  IF has_table_privilege('anon', 'public.signed_waivers', 'SELECT') THEN
    RAISE EXCEPTION '449 SELF-CHECK FAILED: anon retains SELECT on signed_waivers';
  END IF;

  -- ── 7.2 meta_access_token must be blocked for authenticated ───────────────

  IF has_column_privilege(
    'authenticated', 'public.whatsapp_channels', 'meta_access_token', 'SELECT'
  ) THEN
    RAISE EXCEPTION
      '449 SELF-CHECK FAILED: authenticated can still SELECT meta_access_token '
      'from whatsapp_channels — token credential exposed';
  END IF;

  -- ── 7.3 authenticated must have no write access on whatsapp_channels ──────

  IF has_table_privilege('authenticated', 'public.whatsapp_channels', 'DELETE') THEN
    RAISE EXCEPTION
      '449 SELF-CHECK FAILED: authenticated has DELETE on whatsapp_channels';
  END IF;

  IF has_table_privilege('authenticated', 'public.whatsapp_channels', 'INSERT') THEN
    RAISE EXCEPTION
      '449 SELF-CHECK FAILED: authenticated has INSERT on whatsapp_channels';
  END IF;

  IF has_table_privilege('authenticated', 'public.whatsapp_channels', 'UPDATE') THEN
    RAISE EXCEPTION
      '449 SELF-CHECK FAILED: authenticated has UPDATE on whatsapp_channels — '
      'all channel mutations are service_role only';
  END IF;

  -- ── 7.4 authenticated CAN SELECT non-credential metadata columns ──────────

  IF NOT has_column_privilege(
    'authenticated', 'public.whatsapp_channels', 'phone_number', 'SELECT'
  ) THEN
    RAISE EXCEPTION
      '449 SELF-CHECK FAILED: authenticated cannot SELECT phone_number '
      'from whatsapp_channels — over-revoked';
  END IF;

  IF NOT has_column_privilege(
    'authenticated', 'public.whatsapp_channels', 'display_name', 'SELECT'
  ) THEN
    RAISE EXCEPTION
      '449 SELF-CHECK FAILED: authenticated cannot SELECT display_name '
      'from whatsapp_channels — over-revoked';
  END IF;

  -- ── 7.5 otp_code must be blocked for authenticated on contract_signers ────

  IF has_column_privilege(
    'authenticated', 'public.contract_signers', 'otp_code', 'SELECT'
  ) THEN
    RAISE EXCEPTION
      '449 SELF-CHECK FAILED: authenticated can SELECT otp_code '
      'from contract_signers — OTP value exposed';
  END IF;

  -- ── 7.6 authenticated CAN SELECT/INSERT/UPDATE on contracts ──────────────

  -- has_table_privilege returns TRUE when column-level SELECT exists on any column.
  IF NOT has_table_privilege('authenticated', 'public.contracts', 'SELECT') THEN
    RAISE EXCEPTION
      '449 SELF-CHECK FAILED: authenticated cannot SELECT from contracts';
  END IF;

  IF NOT has_table_privilege('authenticated', 'public.contracts', 'INSERT') THEN
    RAISE EXCEPTION
      '449 SELF-CHECK FAILED: authenticated cannot INSERT into contracts';
  END IF;

  -- ── 7.7 authenticated CAN SELECT/INSERT/UPDATE/DELETE on contract_templates ─

  IF NOT has_table_privilege('authenticated', 'public.contract_templates', 'SELECT') THEN
    RAISE EXCEPTION
      '449 SELF-CHECK FAILED: authenticated cannot SELECT from contract_templates';
  END IF;

  IF NOT has_table_privilege('authenticated', 'public.contract_templates', 'DELETE') THEN
    RAISE EXCEPTION
      '449 SELF-CHECK FAILED: authenticated cannot DELETE from contract_templates';
  END IF;

  -- ── 7.8 authenticated CAN SELECT/INSERT/UPDATE on waiver_templates ─────────

  IF NOT has_table_privilege('authenticated', 'public.waiver_templates', 'SELECT') THEN
    RAISE EXCEPTION
      '449 SELF-CHECK FAILED: authenticated cannot SELECT from waiver_templates';
  END IF;

  IF NOT has_table_privilege('authenticated', 'public.waiver_templates', 'INSERT') THEN
    RAISE EXCEPTION
      '449 SELF-CHECK FAILED: authenticated cannot INSERT into waiver_templates';
  END IF;

  -- ── 7.9 authenticated CAN SELECT from signed_waivers ─────────────────────

  IF NOT has_table_privilege('authenticated', 'public.signed_waivers', 'SELECT') THEN
    RAISE EXCEPTION
      '449 SELF-CHECK FAILED: authenticated cannot SELECT from signed_waivers';
  END IF;

  IF has_table_privilege('authenticated', 'public.signed_waivers', 'INSERT') THEN
    RAISE EXCEPTION
      '449 SELF-CHECK FAILED: authenticated has INSERT on signed_waivers — '
      'signing is service_role only';
  END IF;

  -- ── 7.10 service_role retains full access ─────────────────────────────────

  IF NOT has_table_privilege('service_role', 'public.contracts', 'DELETE') THEN
    RAISE EXCEPTION
      '449 SELF-CHECK FAILED: service_role lost DELETE on contracts';
  END IF;

  IF NOT has_table_privilege('service_role', 'public.whatsapp_channels', 'INSERT') THEN
    RAISE EXCEPTION
      '449 SELF-CHECK FAILED: service_role lost INSERT on whatsapp_channels';
  END IF;

  IF NOT has_table_privilege('service_role', 'public.waiver_templates', 'DELETE') THEN
    RAISE EXCEPTION
      '449 SELF-CHECK FAILED: service_role lost DELETE on waiver_templates';
  END IF;

  IF NOT has_table_privilege('service_role', 'public.signed_waivers', 'INSERT') THEN
    RAISE EXCEPTION
      '449 SELF-CHECK FAILED: service_role lost INSERT on signed_waivers';
  END IF;

  RAISE NOTICE
    '449_least_privilege_acl: PASS — '
    'anon excluded on all six tables, meta_access_token blocked, otp_code blocked, '
    'no authenticated writes to whatsapp_channels or signed_waivers, '
    'contracts/contract_templates/waiver_templates accessible to authenticated, '
    'service_role full access confirmed';
END;
$$;
