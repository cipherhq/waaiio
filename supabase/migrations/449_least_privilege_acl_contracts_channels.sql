-- 449: Least-privilege ACL for contracts, contract_signers, contract_templates,
--      whatsapp_channels, waiver_templates, and signed_waivers
--
-- Problem A (staging) — contracts/contract_signers/contract_templates/waiver_templates have NO
--   grants for authenticated. Every dashboard query returns a swallowed 42501
--   that shows as an empty list.
-- Problem B (production) — these same tables have BROAD table-level grants to
--   authenticated (via ALTER DEFAULT PRIVILEGES), which is too permissive.
-- Problem C (both envs) — whatsapp_channels grants authenticated table-level
--   SELECT (M293), meaning meta_access_token is readable by any authenticated
--   session including admin sessions via the is_admin RLS policy.
--
-- Target shape after this migration:
--   contracts / contract_signers:
--     service_role  → SELECT, INSERT, UPDATE, DELETE
--     authenticated → column-level SELECT (non-credential columns only) +
--                     column-level INSERT + UPDATE (no token/OTP/server-managed cols)
--                     RLS "Business owners manage their contracts/signers" still applies
--     anon          → nothing
--
--   contract_templates:
--     service_role  → SELECT, INSERT, UPDATE, DELETE
--     authenticated → column-level SELECT + INSERT + UPDATE + DELETE
--                     RLS "Business owners manage templates" still applies
--     anon          → nothing
--
--   whatsapp_channels:
--     service_role  → SELECT, INSERT, UPDATE, DELETE (unchanged from M293)
--     authenticated → column-level SELECT on metadata-only columns
--                     (meta_access_token excluded)
--                     NO UPDATE — all channel mutations are server-side (service_role)
--                     NO INSERT, NO DELETE
--     anon          → nothing (unchanged from M293)
--
--   waiver_templates:
--     service_role  → SELECT, INSERT, UPDATE, DELETE
--     authenticated → column-level SELECT + INSERT + UPDATE
--                     (token auto-generated by DEFAULT; not in INSERT/UPDATE list)
--                     RLS "owners_manage_waiver_templates" gates rows
--     anon          → nothing
--
--   signed_waivers:
--     service_role  → SELECT, INSERT, UPDATE, DELETE
--     authenticated → column-level SELECT only
--                     Signing is public (via /api/waivers/sign using service_role)
--     anon          → nothing
--
-- Idempotent: GRANT is a no-op if the privilege already exists; REVOKE is a
-- no-op if the privilege does not exist.
--
-- Defense-in-depth: REVOKE FROM PUBLIC on all six tables (in case of future
-- inherited grants), plus explicit column-level REVOKE on every credential
-- column (token, otp_code, meta_access_token, status, signed_at, otp_*).
-- This ensures that even if a column-level grant to PUBLIC or a named role
-- was issued by any grantor, the migration cleans it up unconditionally.
--
-- Behavioral triggers (B4/B5):
--   contracts_signing_mode_immutable — prevents signing_mode changes once a
--     contract leaves 'pending' state, for ALL roles including service_role.
--   contract_signers_lock_on_signed  — prevents any modification to a
--     contract_signers row once the parent contract is 'signed', and blocks
--     authenticated DELETE of contract_signers at all times.

